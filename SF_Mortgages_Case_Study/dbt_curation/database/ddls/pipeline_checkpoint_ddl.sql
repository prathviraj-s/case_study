CREATE SCHEMA IF NOT EXISTS MY_DB.CONTROL;

CREATE TABLE IF NOT EXISTS
MY_DB.CONTROL.PIPELINE_CHECKPOINT
(
    DAG_ID                  VARCHAR,
    SOURCE_NAME             VARCHAR,
    TARGET_TABLE            VARCHAR,
    LAST_SUCCESS_PARTITION  TIMESTAMP_NTZ,
    STATUS                  VARCHAR,
    UPDATED_AT              TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (DAG_ID, SOURCE_NAME)
);
