CREATE OR REPLACE PIPE MORTGAGE_DB.STANDARD.MORTGAGE_APPLICATIONS_PIPE
    AUTO_INGEST = TRUE
AS
COPY INTO MORTGAGE_DB.STANDARD.STAGE_MORTGAGE_APPLICATIONS
(
    RAW_DATA,
    SOURCE_FILE,
    LOAD_TIMESTAMP
)
FROM
(
    SELECT
        $1,
        METADATA$FILENAME,
        CURRENT_TIMESTAMP()
    FROM @MORTGAGE_DB.STANDARD.JSON_STAGE
);