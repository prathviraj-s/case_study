CREATE OR REPLACE PIPE MORTGAGE_DB.STANDARD.CREDIT_BUREAU_PIPE
    AUTO_INGEST = TRUE
AS
COPY INTO MORTGAGE_DB.STANDARD.STAGE_CREDIT_BUREAU
(
    SSN,
    FICO,
    MONTHLY_DEBT,
    SOURCE_FILE,
    LOAD_TIMESTAMP
)
FROM
(
    SELECT
        $1,
        $2,
        $3,
        METADATA$FILENAME,
        CURRENT_TIMESTAMP()
    FROM @MORTGAGE_DB.STANDARD.CSV_STAGE
);
